import { useEffect, useState } from 'react';
import { FileText, Plus } from 'lucide-react';
import { PageHeader } from '../components/layout';
import { Heading } from '@astryxdesign/core/Heading';
import {
  Badge, Button, Card, Drawer, EmptyState, ErrorState, Field, Modal, Pagination, TableSkeleton, useToast,
} from '../components/ui';
import { useApi } from '../lib/hooks';
import { api, download, ApiError } from '../lib/api';
import { formatDate, timeAgo } from '../lib/format';
import { useAuth } from '../lib/auth';

type ReportType = { key: string; name: string; description: string };
type ReportRow = { id: string; type: string; title: string; status: string; createdAt: string; generatedBy: string | null };
type ReportDetail = {
  id: string; type: string; title: string; status: string; createdAt: string;
  summary: {
    kpis: { label: string; value: string | number }[];
    tables: { title: string; columns: { key: string; label: string }[]; rows: Record<string, unknown>[] }[];
    notes: string[]; window: { from: string | null; to: string | null }; generatedAt: string;
  };
  bodyMd: string;
};

export default function ReportsPage() {
  const { permissions } = useAuth();
  const toast = useToast();
  const [page, setPage] = useState(1);
  const [generateOpen, setGenerateOpen] = useState(false);
  const [presetType, setPresetType] = useState('executive');
  const [selected, setSelected] = useState<string | null>(null);
  const [busy, setBusy] = useState(false);

  const types = useApi<ReportType[]>('/reports/types');
  const reports = useApi<{ data: ReportRow[]; meta: { page: number; limit: number; total: number; totalPages: number } }>(`/reports?page=${page}&limit=15`);
  const detail = useApi<ReportDetail>(selected ? `/reports/${selected}` : null);

  const remove = async () => {
    if (!selected) return;
    setBusy(true);
    try {
      await api.del(`/reports/${selected}`);
      toast.push('success', 'Report deleted');
      setSelected(null); reports.refresh();
    } catch (err) { toast.push('error', 'Could not delete', err instanceof ApiError ? err.message : undefined); }
    finally { setBusy(false); }
  };

  return (
    <>
      <PageHeader title="Reports and analytics" subtitle="Reports are generated on demand from stored records. Export as Markdown, CSV or JSON."
        actions={<Button variant="primary" icon={<Plus size={14} aria-hidden="true" />} onClick={() => setGenerateOpen(true)}>Generate report</Button>} />

      <Heading level={2} className="card-title" style={{ marginBottom: 10 }}>Report types</Heading>
      <div className="feature-grid" style={{ marginBottom: 16 }}>
        {(types.data ?? []).map((type) => (
          <button key={type.key} type="button" className="card feature" style={{ textAlign: 'left', cursor: 'pointer' }}
            onClick={() => { setPresetType(type.key); setGenerateOpen(true); }}>
            <div className="row" style={{ gap: 8, marginBottom: 6 }}>
              <FileText size={14} aria-hidden="true" color="var(--color-success)" />
              <span style={{ fontWeight: 600 }}>{type.name}</span>
            </div>
            <p>{type.description}</p>
          </button>
        ))}
      </div>

      <Card title="Generated reports" subtitle="Newest first" bodyClass="">
        {reports.loading && !reports.data ? <TableSkeleton rows={5} cols={4} /> : reports.error ? <ErrorState message={reports.error} onRetry={reports.refresh} /> : (
          <>
            <div className="table-wrap">
              <table className="data">
                <thead><tr><th>Report</th><th>Type</th><th>Generated by</th><th>Status</th><th className="right">Created</th><th /></tr></thead>
                <tbody>
                  {reports.data?.data.map((report) => (
                    <tr key={report.id}>
                      <td style={{ fontWeight: 550 }}>{report.title}</td>
                      <td><Badge tone="neutral">{report.type}</Badge></td>
                      <td className="small muted">{report.generatedBy ?? '—'}</td>
                      <td><Badge tone="mint">{report.status}</Badge></td>
                      <td className="right tiny faint">{timeAgo(report.createdAt)}</td>
                      <td className="right"><Button size="sm" variant="ghost" onClick={() => setSelected(report.id)}>Open</Button></td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
            {reports.data?.data.length === 0 && <EmptyState title="No reports yet" body="Generate one from the cards above. It will use the records currently in this workspace." icon={<FileText size={18} aria-hidden="true" />} />}
            {reports.data && reports.data.data.length > 0 && <Pagination page={reports.data.meta.page} totalPages={reports.data.meta.totalPages} total={reports.data.meta.total} onPage={setPage} />}
          </>
        )}
      </Card>

      <Drawer open={Boolean(selected)} onClose={() => setSelected(null)} title={detail.data?.title ?? 'Report'} subtitle={detail.data ? `${formatDate(detail.data.createdAt)} · ${detail.data.type}` : undefined}
        footer={detail.data ? (
          <div className="row wrap" style={{ marginLeft: 'auto', gap: 6 }}>
            {permissions.canAdmin && <Button size="sm" variant="danger" onClick={remove} loading={busy}>Delete</Button>}
            <Button size="sm" onClick={() => download(`/reports/${detail.data!.id}/download?format=csv`, `${detail.data!.type}.csv`).catch((err) => toast.push('error', 'Download failed', err.message))}>CSV</Button>
            <Button size="sm" onClick={() => download(`/reports/${detail.data!.id}/download?format=md`, `${detail.data!.type}.md`).catch((err) => toast.push('error', 'Download failed', err.message))}>Markdown</Button>
            <Button size="sm" variant="primary" onClick={() => download(`/reports/${detail.data!.id}/download?format=json`, `${detail.data!.type}.json`).catch((err) => toast.push('error', 'Download failed', err.message))}>JSON</Button>
          </div>
        ) : undefined}>
        {detail.loading && <TableSkeleton rows={6} cols={2} />}
        {detail.error && <ErrorState message={detail.error} onRetry={detail.refresh} />}
        {detail.data && (
          <>
            <div className="grid grid-2" style={{ gap: 8 }}>
              {detail.data.summary.kpis.map((kpi) => (
                <div key={kpi.label} className="card" style={{ padding: 10 }}>
                  <p className="tiny faint">{kpi.label}</p>
                  <p style={{ fontSize: 19, fontWeight: 650 }}>{kpi.value}</p>
                </div>
              ))}
            </div>
            {detail.data.summary.tables.map((table) => (
              <div key={table.title}>
                <p className="label" style={{ marginBottom: 6 }}>{table.title}</p>
                <div className="table-wrap" style={{ border: '1px solid #1e2b38', borderRadius: 8 }}>
                  <table className="data">
                    <thead><tr>{table.columns.map((column) => <th key={column.key}>{column.label}</th>)}</tr></thead>
                    <tbody>
                      {table.rows.slice(0, 12).map((row, index) => (
                        <tr key={index}>
                          {table.columns.map((column) => <td key={column.key} className="tiny">{String(row[column.key] ?? '—')}</td>)}
                        </tr>
                      ))}
                    </tbody>
                  </table>
                </div>
                {table.rows.length > 12 && <p className="tiny faint" style={{ marginTop: 4 }}>Showing 12 of {table.rows.length}. Export for the full table.</p>}
              </div>
            ))}
            {detail.data.summary.notes.length > 0 && (
              <div>
                <p className="label">Notes</p>
                <ul className="small muted" style={{ margin: '4px 0 0', paddingLeft: 18 }}>
                  {detail.data.summary.notes.map((note) => <li key={note}>{note}</li>)}
                </ul>
              </div>
            )}
            <div>
              <p className="label">Markdown source</p>
              <pre className="code-block" style={{ maxHeight: 260 }}>{detail.data.bodyMd}</pre>
            </div>
          </>
        )}
      </Drawer>

      <GenerateModal open={generateOpen} preset={presetType} onClose={() => setGenerateOpen(false)} onCreated={(id) => { reports.refresh(); setSelected(id); }} />
    </>
  );
}

function GenerateModal({ open, preset, onClose, onCreated }: { open: boolean; preset: string; onClose: () => void; onCreated: (id: string) => void }) {
  const toast = useToast();
  const types = useApi<ReportType[]>('/reports/types');
  const [type, setType] = useState(preset);
  const [from, setFrom] = useState('');
  const [to, setTo] = useState('');
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    if (open) setType(preset);
  }, [open, preset]);

  const generate = async () => {
    setBusy(true); setError(null);
    try {
      const report = await api.post<{ id: string }>('/reports/generate', {
        type,
        from: from ? new Date(`${from}T00:00:00Z`).toISOString() : undefined,
        to: to ? new Date(`${to}T23:59:59Z`).toISOString() : undefined,
      });
      toast.push('success', 'Report generated');
      onCreated(report.id); onClose();
    } catch (err) { setError(err instanceof ApiError ? err.message : 'Could not generate the report'); }
    finally { setBusy(false); }
  };

  return (
    <Modal open={open} onClose={onClose} title="Generate a report" subtitle="Built from the records in this workspace at the moment you generate it."
      footer={<><Button variant="ghost" onClick={onClose} type="button">Cancel</Button><Button variant="primary" onClick={generate} loading={busy} type="button">Generate</Button></>}>
      {error && <div className="error-box" role="alert">{error}</div>}
      <Field label="Report type" htmlFor="r-type">
        <select id="r-type" className="select" value={type} onChange={(e) => setType(e.target.value)}>
          {(types.data ?? []).map((item) => <option key={item.key} value={item.key}>{item.name}</option>)}
        </select>
      </Field>
      <div className="grid grid-2">
        <Field label="From" htmlFor="r-from" hint="Optional. Applies to records with a created timestamp."><input id="r-from" type="date" className="input" value={from} onChange={(e) => setFrom(e.target.value)} /></Field>
        <Field label="To" htmlFor="r-to"><input id="r-to" type="date" className="input" value={to} onChange={(e) => setTo(e.target.value)} /></Field>
      </div>
      <p className="tiny faint">Assets and vulnerabilities are current-state tables and ignore the date window. Incident, detection and simulation tables respect it.</p>
    </Modal>
  );
}
