/**
 * Translate the applied SQLite schema into PostgreSQL DDL.
 *
 * The source of truth is the schema that is actually present in a database
 * (sqlite_master), not the migration files, so a partially migrated or older
 * installation cannot produce a schema that differs from the running app.
 *
 * Only syntax is translated. Constraints, defaults and indexes are preserved
 * verbatim apart from column types and the PRAGMA lines, which have no meaning
 * in PostgreSQL.
 */
import { DatabaseSync } from 'node:sqlite';
import { existsSync } from 'node:fs';

const TYPE_MAP = [
  [/\bINTEGER\b/g, 'bigint'],
  [/\bREAL\b/g, 'double precision'],
  [/\bTEXT\b/g, 'text'],
  [/\bBLOB\b/g, 'bytea'],
];

const SKIP_OBJECTS = /^(sqlite_|_cf_|sqlite_sequence)/i;

export function translateStatement(sql) {
  let out = sql
    .split('\n')
    .filter((line) => !/^\s*PRAGMA\b/i.test(line))
    .join('\n')
    .trim();
  for (const [pattern, replacement] of TYPE_MAP) out = out.replace(pattern, replacement);
  // SQLite allows a bare boolean-ish default; PostgreSQL keeps 0/1 for bigint.
  out = out.replace(/DEFAULT\s+datetime\('now'\)/gi, 'DEFAULT now()');
  out = out.replace(/\bWITHOUT\s+ROWID\b/gi, '');
  out = out.replace(/\bSTRICT\b/gi, '');
  return out;
}

export function readSchema(dbPath) {
  if (!existsSync(dbPath)) throw new Error(`Database not found: ${dbPath}`);
  const db = new DatabaseSync(dbPath, { readOnly: true });
  try {
    const rows = db.prepare(
      "SELECT type, name, tbl_name, sql FROM sqlite_master WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%' ORDER BY rowid",
    ).all();
    return rows.filter((row) => !SKIP_OBJECTS.test(row.name));
  } finally {
    db.close();
  }
}

export function buildPostgresSchema(dbPath) {
  const objects = readSchema(dbPath);
  const tables = objects.filter((o) => o.type === 'table');
  const indexes = objects.filter((o) => o.type === 'index');
  const triggers = objects.filter((o) => o.type === 'trigger');
  if (triggers.length) {
    throw new Error(`Trigger translation is not implemented (${triggers.map((t) => t.name).join(', ')})`);
  }
  const parts = [
    '-- Generated by scripts/pg/generate-schema.mjs. Do not edit by hand.',
    '-- Source: the applied SQLite schema. Target: PostgreSQL 15 or newer.',
    'BEGIN;',
    '',
  ];
  for (const table of tables) parts.push(`${translateStatement(table.sql)};`, '');
  for (const index of indexes) parts.push(`${translateStatement(index.sql)};`, '');
  if (indexes.length) parts.push('');
  parts.push('COMMIT;', '');
  return { sql: parts.join('\n'), tables: tables.length, indexes: indexes.length, objects };
}

/** Tenant-owned tables: every one must carry org_id for application level scoping. */
export function schemaReport(dbPath) {
  const { sql, tables, indexes } = buildPostgresSchema(dbPath);
  const db = new DatabaseSync(dbPath, { readOnly: true });
  try {
    const names = db.prepare("SELECT name FROM sqlite_master WHERE type = 'table' AND name NOT LIKE 'sqlite_%' ORDER BY name").all().map((r) => r.name);
    const tenantTables = names.filter((name) => db.prepare(`PRAGMA table_info(${name})`).all().some((c) => c.name === 'org_id'));
    return { sql, tables, indexes, names, tenantTables };
  } finally {
    db.close();
  }
}
